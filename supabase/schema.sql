-- 1. Create Enums
CREATE TYPE user_role AS ENUM ('Owner', 'Manager', 'Staff');
CREATE TYPE movement_type AS ENUM ('Stock In', 'Stock Out', 'Adjustment');

-- 2. Profiles Table
CREATE TABLE public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  role user_role NOT NULL DEFAULT 'Staff',
  is_active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Categories Table
CREATE TABLE public.categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Products Table
CREATE TABLE public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  category_id BIGINT REFERENCES public.categories(id) ON DELETE RESTRICT,
  price NUMERIC(12, 2) NOT NULL DEFAULT 0.00, -- in MYR
  stock INT NOT NULL DEFAULT 0,
  threshold INT NOT NULL DEFAULT 10,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Stock Movements Table
CREATE TABLE public.stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT REFERENCES public.products(id) ON DELETE CASCADE NOT NULL,
  sku TEXT NOT NULL,
  quantity_change INT NOT NULL,
  stock_before INT NOT NULL,
  stock_after INT NOT NULL,
  activity movement_type NOT NULL,
  source TEXT NOT NULL,
  created_by UUID REFERENCES public.profiles(id) NOT NULL,
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Helper Function: Get Current User Role
CREATE OR REPLACE FUNCTION public.get_current_role()
RETURNS user_role AS $$
  SELECT role FROM public.profiles WHERE id = auth.uid() LIMIT 1;
$$ LANGUAGE sql STABLE SECURITY DEFINER;

-- 7. Trigger: Update Product Stock on Movement Insert
CREATE OR REPLACE FUNCTION public.handle_stock_movement()
RETURNS TRIGGER AS $$
BEGIN
  UPDATE public.products
  SET stock = stock + NEW.quantity_change
  WHERE id = NEW.product_id;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER tr_after_stock_movement_insert
AFTER INSERT ON public.stock_movements
FOR EACH ROW
EXECUTE FUNCTION public.handle_stock_movement();

-- 8. Enable Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stock_movements ENABLE ROW LEVEL SECURITY;

-- 9. RLS Policies
-- Profiles
CREATE POLICY "Allow read profiles" ON public.profiles
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Owner manage profiles" ON public.profiles
  FOR ALL TO authenticated
  USING (public.get_current_role() = 'Owner');

-- Categories
CREATE POLICY "Allow read categories" ON public.categories
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Owner/Manager manage categories" ON public.categories
  FOR ALL TO authenticated
  USING (public.get_current_role() IN ('Owner', 'Manager'));

-- Products
CREATE POLICY "Allow read products" ON public.products
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Owner/Manager manage products" ON public.products
  FOR ALL TO authenticated
  USING (public.get_current_role() IN ('Owner', 'Manager'));

-- Stock Movements
CREATE POLICY "Allow read movements" ON public.stock_movements
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Allow insert movements by role" ON public.stock_movements
  FOR INSERT TO authenticated
  WITH CHECK (
    public.get_current_role() IN ('Owner', 'Manager')
    OR (
      public.get_current_role() = 'Staff'
      AND activity IN ('Stock In', 'Adjustment')
    )
  );

-- 10. Auto create Profile on Auth Signup
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, email, name, role)
  VALUES (
    NEW.id,
    NEW.email,
    COALESCE(NEW.raw_user_meta_data->>'name', split_part(NEW.email, '@', 1)),
    COALESCE((NEW.raw_user_meta_data->>'role')::user_role, 'Staff')
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

